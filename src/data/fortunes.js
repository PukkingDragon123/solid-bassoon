export const THAI_DIGITS = ['๐', '๑', '๒', '๓', '๔', '๕', '๖', '๗', '๘', '๙'];

export function toThaiNumber(n) {
  return String(n)
    .split('')
    .map((d) => THAI_DIGITS[Number(d)] ?? d)
    .join('');
}

